// A UI theme = the full set of interface colours, as RGB triplets, in the same
// order AppWindow stores them. Shared by Project (the selectable list) and
// AppWindow (applying the palette). Keep themeNames and themeColors in sync.

struct ThemeColors {
	unsigned char bg[3] ;      // background
	unsigned char fg[3] ;      // normal text / foreground
	unsigned char border[3] ;  // border
	unsigned char svfe[3] ;    // songview FE
	unsigned char sv00[3] ;    // songview 00
	unsigned char hi1[3] ;     // highlight 1
	unsigned char hi2[3] ;     // highlight 2
	unsigned char console[3] ; // console
	unsigned char cursor[3] ;  // cursor
	unsigned char play[3] ;    // playing
	unsigned char mute[3] ;    // muted
	unsigned char row1[3] ;    // row number
	unsigned char row2[3] ;    // row number (alt)
	unsigned char beat[3] ;    // major beat
} ;

